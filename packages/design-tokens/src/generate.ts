import { ColorScheme } from '@daycraft/domain';

import { hueColors, semanticColors, shadowColors } from './colors';
import { durations, easing, popScale, springs, springToCssEasing } from './motion';
import { floatShadow, radii, shadows } from './shape';
import { fontFamilies, typeScale, type TypeStyle } from './typography';

const HEADER = '/* GENERATED by @daycraft/design-tokens (`bun run build` in that package). Do not edit by hand. */';

function rem(px: number): string {
  return `${Number((px / 16).toFixed(5))}rem`;
}

function round(value: number): number {
  return Number(value.toFixed(2));
}

function block(selector: string, lines: string[], indent = ''): string {
  return [`${indent}${selector} {`, ...lines.map((line) => `${indent}  ${line}`), `${indent}}`].join('\n');
}

function familyVariable(style: TypeStyle): string {
  return `var(--font-${fontFamilies[style.weight].className})`;
}

function hueVariables(): string[] {
  return Object.entries(hueColors).map(([hue, hex]) => `--color-${hue}: ${hex};`);
}

function radiusVariables(): string[] {
  return Object.entries(radii).map(([name, { px }]) => `--radius-${name}: ${rem(px)};`);
}

const cubicBezier = `cubic-bezier(${easing.snap.join(', ')})`;
const springSnap = springToCssEasing(springs.snap);

/** Theme CSS for the mobile app (Tailwind v4 through Uniwind; light/dark as `@variant`s). */
export function generateUniwindCss(): string {
  const schemeBlock = (scheme: ColorScheme): string =>
    block(
      `@variant ${scheme}`,
      Object.entries(semanticColors[scheme]).map(([name, value]) => `--color-${name}: ${value};`),
      '    ',
    );

  const theme = block('@theme', [
    '/* Activity hues: the same in light and dark */',
    ...hueVariables(),
    '',
    '/* Type families: one embedded family per weight (React Native has no font stacks) */',
    ...Object.values(fontFamilies).map((family) => `--font-${family.className}: '${family.native}';`),
    '',
    '/* Type sizes (the type-* presets below carry line height, tracking and family) */',
    ...Object.entries(typeScale).map(([name, style]) => `--text-${name}: ${rem(style.size)};`),
    '',
    '/* Radii: pills use rounded-full */',
    ...radiusVariables(),
  ]);

  const presets = Object.entries(typeScale).map(([name, style]) => {
    const lines = [`font-size: ${style.size}px;`];
    if (style.lineHeight !== undefined) lines.push(`line-height: ${round(style.size * style.lineHeight)}px;`);
    if (style.letterSpacing !== undefined) lines.push(`letter-spacing: ${round(style.size * style.letterSpacing)}px;`);
    lines.push(`font-family: ${familyVariable(style)};`);
    return block(`.type-${name}`, lines, '  ');
  });

  return [
    HEADER,
    '',
    '@layer theme {',
    '  :root {',
    schemeBlock(ColorScheme.LIGHT),
    schemeBlock(ColorScheme.DARK),
    '  }',
    '}',
    '',
    theme,
    '',
    block('@utility shadow-float', [
      `box-shadow: ${floatShadow(`light-dark(${shadowColors.light}, ${shadowColors.dark})`)};`,
    ]),
    block('@utility shadow-lift', [`box-shadow: ${shadows.lift};`]),
    '',
    '/* Type presets: absolute px, because React Native has no unitless line height */',
    '@layer components {',
    presets.join('\n'),
    '}',
    '',
  ].join('\n');
}

/** Theme CSS for the web app (Tailwind v4; dark mode is the `.dark` class on <html>). */
export function generateTailwindCss(): string {
  const schemeVariables = (scheme: ColorScheme): string[] => [
    ...Object.entries(semanticColors[scheme]).map(([name, value]) => `--${name}: ${value};`),
    `--shadow-float-color: ${shadowColors[scheme]};`,
    `--thumb-shadow: ${shadows.thumb[scheme]};`,
    `color-scheme: ${scheme};`,
  ];

  const typeVariables = Object.entries(typeScale).flatMap(([name, style]) => {
    const lines = [`--text-${name}: ${rem(style.size)};`];
    if (style.lineHeight !== undefined) lines.push(`--text-${name}--line-height: ${style.lineHeight};`);
    if (style.letterSpacing !== undefined) lines.push(`--text-${name}--letter-spacing: ${style.letterSpacing}em;`);
    lines.push(`--text-${name}--font-weight: ${style.weight};`);
    return lines;
  });

  const theme = block('@theme', [
    '/* Activity hues: the same in light and dark */',
    ...hueVariables(),
    '',
    '--font-sans: var(--font-onest), ui-sans-serif, system-ui, sans-serif;',
    '',
    ...typeVariables,
    '',
    '/* Radii: pills use rounded-full */',
    ...radiusVariables(),
    '',
    '--shadow-float: 0 1px 2px var(--shadow-float-color), 0 12px 32px var(--shadow-float-color);',
    `--shadow-lift: ${shadows.lift};`,
    '--shadow-thumb: var(--thumb-shadow);',
    '',
    `--ease-snap: ${cubicBezier};`,
    `--ease-spring-snap: ${springSnap.easing};`,
    `--spring-snap-duration: ${springSnap.durationMs}ms;`,
    `--animate-sheet-up: sheet-up ${durations.sheetUp / 1000}s var(--ease-snap);`,
    `--animate-fade-in: fade-in ${durations.fadeIn / 1000}s ease;`,
    `--animate-pop: pop ${durations.pop / 1000}s ease;`,
    '',
    '@keyframes sheet-up { from { transform: translateY(48px); opacity: 0; } to { transform: none; opacity: 1; } }',
    '@keyframes fade-in { from { opacity: 0; } to { opacity: 1; } }',
    `@keyframes pop { 0% { transform: scale(${popScale[0]}); } 55% { transform: scale(${popScale[1]}); } 100% { transform: scale(${popScale[2]}); } }`,
  ]);

  const presets = Object.entries(typeScale).map(([name, style]) => {
    const lines = [`font-size: var(--text-${name});`];
    if (style.lineHeight !== undefined) lines.push(`line-height: var(--text-${name}--line-height);`);
    if (style.letterSpacing !== undefined) lines.push(`letter-spacing: var(--text-${name}--letter-spacing);`);
    lines.push(`font-weight: ${style.weight};`);
    return block(`@utility type-${name}`, lines);
  });

  return [
    HEADER,
    '',
    '@custom-variant dark (&:where(.dark, .dark *));',
    '',
    block(':root', schemeVariables(ColorScheme.LIGHT)),
    '',
    block('.dark', schemeVariables(ColorScheme.DARK)),
    '',
    block(
      '@theme inline',
      Object.keys(semanticColors.light).map((name) => `--color-${name}: var(--${name});`),
    ),
    '',
    theme,
    '',
    '/* Type presets as utilities, so they work with @apply and variants (md:type-display) */',
    presets.join('\n'),
    '',
  ].join('\n');
}
